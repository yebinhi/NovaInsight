def current_lang():
    lang = request.cookies.get("nova_lang", "zh")
    return lang if lang in LOCALES else "zh"


def t(key, **kwargs):
    lang = current_lang()
    text = STRINGS[lang].get(key) or STRINGS["en"][key]
    return text.format(**kwargs) if kwargs else text


def stage_labels(lang=None):
    return STAGE_LABELS[lang or current_lang()]


def channel_labels(lang=None):
    return CHANNEL_LABELS[lang or current_lang()]
