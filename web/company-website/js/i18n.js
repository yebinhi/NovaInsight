window.novaLang = function () {
  try {
    return localStorage.getItem("nova-lang") === "zh" ? "zh" : "en";
  } catch (error) {
    return "en";
  }
};

window.novaText = function (key) {
  const pack = window.NOVA_COPY[window.novaLang()] || window.NOVA_COPY.en;
  return pack[key] || window.NOVA_COPY.en[key] || "";
};

window.novaApply = function (lang) {
  const next = lang === "zh" ? "zh" : "en";
  try {
    localStorage.setItem("nova-lang", next);
  } catch (error) {
    /* keep the choice for this page only */
  }
  const pack = window.NOVA_COPY[next];
  document.documentElement.lang = next === "zh" ? "zh-Hans" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n")];
    if (value != null) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n-aria")];
    if (value != null) node.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-meta]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n-meta")];
    if (value != null) node.setAttribute("content", value);
  });
  const titleKey = document.body.getAttribute("data-i18n-title");
  if (titleKey && pack[titleKey]) document.title = pack[titleKey];
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", button.getAttribute("data-set-lang") === next ? "true" : "false");
  });
  const toggle = document.querySelector("[data-nav-toggle]");
  if (toggle) {
    const open = toggle.getAttribute("aria-expanded") === "true";
    toggle.textContent = pack[open ? "nav.close" : "nav.menu"];
  }
};

window.novaApply(window.novaLang());

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => window.novaApply(button.getAttribute("data-set-lang")));
});
